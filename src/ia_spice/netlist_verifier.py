"""
Formal LTspice Schematic-to-Netlist Isomorphism Verifier (`ia_spice.netlist_verifier`).

Why this module exists:
-----------------------
Visual schematics (`.asc`) generated by scripts or humans can look reasonable while hiding fatal
electrical bugs: floating pins (`NC_01`), shorted nodes where a wire crosses a terminal, or
swapped transistor collector/emitter pins.

This module uses LTspice's own schematic compiler (`LTspice.exe -netlist file.asc`) to generate
the ground-truth `.net` file, and then formally verifies:
1. ZERO unconnected pins (`NC_` tokens).
2. 100% netlist connectivity match against either an expected connection dictionary or a reference
   `.cir` netlist file (handling passive 2-pin symmetry automatically).
"""

from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

from .simulator import find_ltspice_executable


# Number of circuit nodes per SPICE component prefix
PIN_COUNT_BY_PREFIX = {
    "R": 2,
    "C": 2,
    "L": 2,
    "V": 2,
    "I": 2,
    "D": 2,
    "Q": 3,  # C, B, E
    "J": 3,  # D, G, S
    "M": 4,  # D, G, S, B
}

SYMMETRIC_2PIN_PREFIXES = {"R", "C", "L"}


@dataclass
class NetlistVerificationReport:
    """Formal verification report produced by `verify_asc_netlist`."""
    asc_path: str
    net_path: str
    unconnected_pins: List[str] = field(default_factory=list)
    component_nodes: Dict[str, List[str]] = field(default_factory=dict)
    mismatches: List[str] = field(default_factory=list)
    missing_components: List[str] = field(default_factory=list)

    @property
    def is_clean(self) -> bool:
        return (
            len(self.unconnected_pins) == 0
            and len(self.mismatches) == 0
            and len(self.missing_components) == 0
        )


def parse_spice_netlist_components(net_text: str) -> Tuple[Dict[str, List[str]], List[str]]:
    """
    Extract component-to-node connectivity from a SPICE `.net` or `.cir` text.
    Returns `(component_nodes_dict, unconnected_pin_tokens)`.
    """
    comp_nodes: Dict[str, List[str]] = {}
    nc_tokens: List[str] = []

    for raw_line in net_text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("*") or line.startswith(".") or line.startswith(";"):
            continue

        # Find any unconnected pin markers generated by LTspice (`NC_01`, `NC_02`, etc.)
        for m_nc in re.findall(r"\bNC_[0-9a-zA-Z_]*\b", line):
            nc_tokens.append(f"{line.split()[0]}:{m_nc}")

        parts = line.split()
        inst = parts[0].upper()
        prefix = inst[0]

        if prefix in PIN_COUNT_BY_PREFIX and len(parts) >= 1 + PIN_COUNT_BY_PREFIX[prefix]:
            n_pins = PIN_COUNT_BY_PREFIX[prefix]
            nodes = [n.upper() for n in parts[1 : 1 + n_pins]]
            comp_nodes[inst] = nodes
        elif prefix == "X":
            non_param = [p for p in parts[1:] if "=" not in p]
            if len(non_param) >= 2:
                nodes = [n.upper() for n in non_param[:-1]]
                comp_nodes[inst] = nodes

    return comp_nodes, nc_tokens


def compile_asc_to_netlist(asc_path: str, ltspice_exe: Optional[str] = None) -> str:
    """Run `LTspice.exe -netlist <asc_path>` and return the path to the generated `.net` file."""
    abs_asc = os.path.abspath(asc_path)
    if not os.path.isfile(abs_asc):
        raise FileNotFoundError(f"Schematic file not found: {abs_asc}")

    exe = find_ltspice_executable(ltspice_exe)
    net_path = os.path.splitext(abs_asc)[0] + ".net"

    if os.path.exists(net_path):
        try:
            os.remove(net_path)
        except OSError:
            pass

    subprocess.run(
        [exe, "-netlist", abs_asc],
        cwd=os.path.dirname(abs_asc),
        capture_output=True,
        check=True,
        timeout=60,
    )

    if not os.path.isfile(net_path):
        raise RuntimeError(f"LTspice failed to generate netlist file: {net_path}")
    return net_path


def _nodes_match_with_aliasing(
    exp_nodes: List[str],
    act_nodes: List[str],
    alias_map: Dict[str, str],
) -> bool:
    """
    Check if `act_nodes` matches `exp_nodes` where LTspice auto-named internal wires (`N001`, `N002`, ...)
    are allowed to form a consistent 1-to-1 bijection with internal reference node names.
    """
    if len(exp_nodes) != len(act_nodes):
        return False
    trial_map = dict(alias_map)
    for e_node, a_node in zip(exp_nodes, act_nodes):
        if e_node == a_node:
            continue
        # Allow bijection when either node is an LTspice auto-generated internal net (`N\d+`)
        # or already mapped consistently
        if re.match(r"^N\d+$", a_node) or re.match(r"^N\d+$", e_node):
            if e_node in trial_map and trial_map[e_node] != a_node:
                return False
            if a_node in trial_map.values() and trial_map.get(e_node) != a_node:
                return False
            trial_map[e_node] = a_node
        else:
            return False
    alias_map.update(trial_map)
    return True


def verify_asc_netlist(
    asc_path: str,
    expected_connections: Optional[Dict[str, List[str]]] = None,
    reference_cir_path: Optional[str] = None,
    ltspice_exe: Optional[str] = None,
) -> NetlistVerificationReport:
    """
    Compile `asc_path` via `LTspice.exe -netlist`, verify zero `NC_` floating pins, and optionally
    verify that all component node connections match `expected_connections` or `reference_cir_path`
    (up to consistent 1-to-1 renaming of unlabelled internal wire nodes `N001`, `N002`, etc.).
    """
    net_path = compile_asc_to_netlist(asc_path, ltspice_exe=ltspice_exe)
    with open(net_path, "r", encoding="latin-1", errors="replace") as f:
        net_text = f.read()

    actual_map, nc_list = parse_spice_netlist_components(net_text)
    report = NetlistVerificationReport(
        asc_path=os.path.abspath(asc_path),
        net_path=net_path,
        unconnected_pins=nc_list,
        component_nodes=actual_map,
    )

    ref_map: Dict[str, List[str]] = {}
    if reference_cir_path:
        with open(reference_cir_path, "r", encoding="latin-1", errors="replace") as f:
            cir_map, _ = parse_spice_netlist_components(f.read())
            ref_map.update(cir_map)

    if expected_connections:
        for k, v in expected_connections.items():
            ref_map[k.upper()] = [n.upper() for n in v]

    alias_map: Dict[str, str] = {}
    for comp_name, exp_nodes in ref_map.items():
        act_key = comp_name
        if act_key not in actual_map and act_key.startswith("X") and ("X" + act_key) in actual_map:
            act_key = "X" + act_key
        if act_key not in actual_map:
            # Skip optional simulation-only test sources (IPULSE=0) or renamed ideal DC supply decoupling caps (C_DEC* / C_DECOUPLE*)
            if comp_name.startswith("IPULSE") or comp_name.startswith("C_DEC"):
                continue
            report.missing_components.append(comp_name)
            continue
        act_nodes = actual_map[act_key]
        match = _nodes_match_with_aliasing(exp_nodes, act_nodes, alias_map)
        if not match and len(exp_nodes) == 2 and (comp_name[0] in SYMMETRIC_2PIN_PREFIXES or comp_name.startswith("X")):
            match = _nodes_match_with_aliasing(exp_nodes, act_nodes[::-1], alias_map)
        if not match:
            report.mismatches.append(
                f"{comp_name}: expected nodes {exp_nodes}, but .asc netlist connected {act_nodes}"
            )

    return report
